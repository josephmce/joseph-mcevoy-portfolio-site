import { defineArrayMember, defineField, defineType } from "sanity";

export const project = defineType({
  name: "project",
  title: "Project",
  type: "document",
  groups: [
    { name: "content", title: "Content", default: true },
    { name: "details", title: "Details" },
    { name: "media", title: "Media" },
    { name: "links", title: "Links" },
    { name: "seo", title: "SEO" },
  ],
  fields: [
    defineField({
      name: "title",
      title: "Title",
      type: "string",
      group: "content",
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: "slug",
      title: "Slug",
      type: "slug",
      group: "content",
      options: { source: "title", maxLength: 96 },
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: "summary",
      title: "Summary",
      type: "text",
      rows: 3,
      group: "content",
      validation: (Rule) => Rule.required().max(240),
    }),
    defineField({
      name: "featured",
      title: "Featured project",
      type: "boolean",
      group: "details",
      initialValue: false,
    }),
    defineField({
      name: "projectDate",
      title: "Project date",
      type: "date",
      group: "details",
    }),
    defineField({ name: "client", title: "Client", type: "string", group: "details" }),
    defineField({ name: "employer", title: "Employer", type: "string", group: "details" }),
    defineField({ name: "role", title: "Role", type: "string", group: "details" }),
    defineField({ name: "duration", title: "Duration", type: "string", group: "details" }),
    defineField({
      name: "categories",
      title: "Categories",
      type: "array",
      group: "details",
      of: [defineArrayMember({ type: "reference", to: [{ type: "projectCategory" }] })],
      validation: (Rule) => Rule.required().min(1),
    }),
    defineField({
      name: "services",
      title: "Services",
      type: "array",
      group: "details",
      of: [defineArrayMember({ type: "string" })],
      options: { layout: "tags" },
    }),
    defineField({
      name: "technologies",
      title: "Technologies",
      type: "array",
      group: "details",
      of: [defineArrayMember({ type: "string" })],
      options: { layout: "tags" },
    }),
    defineField({
      name: "designTools",
      title: "Design tools",
      type: "array",
      group: "details",
      of: [defineArrayMember({ type: "string" })],
      options: { layout: "tags" },
    }),
    defineField({
      name: "coverImage",
      title: "Cover image",
      type: "image",
      group: "media",
      options: { hotspot: true },
      fields: [
        defineField({ name: "alt", title: "Alternative text", type: "string" }),
      ],
      validation: (Rule) => Rule.required(),
    }),
    defineField({
      name: "gallery",
      title: "Gallery",
      type: "array",
      group: "media",
      of: [
        defineArrayMember({
          name: "galleryItem",
          title: "Gallery item",
          type: "object",
          fields: [
            defineField({
              name: "image",
              title: "Image",
              type: "image",
              options: { hotspot: true },
              validation: (Rule) => Rule.required(),
            }),
            defineField({ name: "alt", title: "Alternative text", type: "string" }),
            defineField({ name: "caption", title: "Caption", type: "string" }),
          ],
          preview: {
            select: { title: "caption", media: "image" },
            prepare({ title, media }) {
              return { title: title || "Gallery image", media };
            },
          },
        }),
      ],
    }),
    defineField({ name: "overview", title: "Overview", type: "blockContent", group: "content" }),
    defineField({ name: "challenge", title: "Challenge", type: "blockContent", group: "content" }),
    defineField({ name: "process", title: "Process", type: "blockContent", group: "content" }),
    defineField({ name: "solution", title: "Solution", type: "blockContent", group: "content" }),
    defineField({ name: "outcome", title: "Outcome", type: "blockContent", group: "content" }),
    defineField({ name: "liveUrl", title: "Live URL", type: "url", group: "links" }),
    defineField({ name: "repositoryUrl", title: "Repository URL", type: "url", group: "links" }),
    defineField({ name: "prototypeUrl", title: "Prototype URL", type: "url", group: "links" }),
    defineField({ name: "seo", title: "SEO", type: "seo", group: "seo" }),
  ],
  orderings: [
    {
      title: "Project date, newest",
      name: "projectDateDesc",
      by: [{ field: "projectDate", direction: "desc" }],
    },
  ],
  preview: {
    select: {
      title: "title",
      subtitle: "role",
      media: "coverImage",
    },
  },
});
